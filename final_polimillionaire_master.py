def retrieve_math(query: str, index, chunks: list,
                  top_k: int = 4, schema_boost: int = 1) -> list:
    """
    Return up to top_k chunks: the classified schema first, then nearest
    worked examples. Guarantees the matching schema chunk is included even
    if dense search misses it.
    """
    schema_id = classify_problem(query)

    try:
        q_vec = np.asarray(_encode_queries([query])).astype(np.float32)
        _, idxs = index.search(q_vec, top_k + 6)
        retrieved = [chunks[i] for i in idxs[0] if 0 <= i < len(chunks)]
    except NameError:
        retrieved = list(chunks)

    # force the classified schema chunk to the front
    schema_chunk = next((c for c in chunks
                         if c["layer"] == "schema" and c["schema_id"] == schema_id),
                        None)
    ordered = ([schema_chunk] if schema_chunk else []) + retrieved

    seen, result = set(), []
    for c in ordered:
        if c is None or c["art_id"] in seen:
            continue
        seen.add(c["art_id"])
        result.append(c)
        if len(result) >= top_k:
            break
    return result


