def _fetch_feed(url: str, timeout: int = RSS_TIMEOUT) -> list:
    try:
        r = requests.get(url, headers=RSS_HEADERS, timeout=timeout)
        if r.status_code != 200 or not r.content:
            return []
        return feedparser.parse(r.content).entries or []
    except Exception:
        return []


def fetch_rss_news(query: str, max_items: int = 5) -> list:
    """
    Aggregates news items from RSS sources based on query overlap.
    Network requests are strictly limited to prevent systemic latency.
    """
    out = []
    keywords = {w.lower() for w in re.findall(r"\w+", query) if len(w) >= 3}

    g_url = NEWS_RSS_FEEDS["google_news_query"].format(q=urllib.parse.quote(query))
    for e in _fetch_feed(g_url)[:max_items]:
        title   = e.get("title", "") or ""
        summary = e.get("summary", "") or ""
        pub     = e.get("published", "") or ""
        link    = e.get("link", "") or ""
        text    = f"[{pub}] {title}. {summary}".strip()
        if len(text) >= 20:
            out.append({"source": "rss:google_news", "text": text, "title": title, "url": link, "query": query})

    topic = [(k, v) for k, v in NEWS_RSS_FEEDS.items() if k != "google_news_query"]
    with ThreadPoolExecutor(max_workers=len(topic)) as ex:
        futs = {ex.submit(_fetch_feed, url): name for name, url in topic}
        for fut in as_completed(futs, timeout=RSS_TIMEOUT + 2):
            name = futs[fut]
            try:
                entries = fut.result()
            except Exception:
                continue
            for e in entries[:RSS_MAX_PER_FEED]:
                title   = e.get("title", "") or ""
                summary = e.get("summary", "") or ""
                blob    = (title + " " + summary).lower()
                if not any(kw in blob for kw in keywords):
                    continue
                pub  = e.get("published", "") or ""
                link = e.get("link", "") or ""
                text = f"[{pub}] {title}. {summary}".strip()
                if len(text) >= 20:
                    out.append({"source": f"rss:{name}", "text": text, "title": title, "url": link, "query": query})

    seen, unique = set(), []
    for it in out:
        k = it["title"][:120]
        if k not in seen:
            seen.add(k)
            unique.append(it)
    return unique[:max_items * 2]


