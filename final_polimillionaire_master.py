import concurrent.futures
import time
import os
import re
import requests

def run_session_speech(category_id: int,
                       use_judge_from_level: int = 1,
                       run_meta_extra: dict = None) -> tuple:
    """Executes the primary speech-mode session architecture."""

    session = requests.Session()
    if not perform_login(session):
        return None, None
    game_state = start_game(session, category_id, mode="speech")
    if not game_state:
        return None, None

    server_sid = game_state["sessionId"]
    cat_name   = CATEGORY_NAMES.get(category_id, "Unknown")

    run_meta = {
        "model_name":            LLM_NAME,
        "math_llm":              MATH_LLM_NAME,
        "embedder":              EMBEDDER_NAME,
        "reranker":              RERANKER_NAME,
        "whisper_model":         WHISPER_NAME,
        "quantization":          "4bit-nf4",
        "category_id":           category_id,
        "category_name":         cat_name,
        "game_mode":             "SPEECH_CONCURRENT",
        "use_judge_from_level":  use_judge_from_level,
        "server_session_id":     server_sid,
        "username":              CREDENTIALS["username"],
        "prompting_strategy":    "zero_shot_self_consistency",
        "notebook_label":        "master",
        "speech_patches":        ["H", "I", "J", "K_dyn", "L", "Concurrency"],
        "low_logprob_thr":       LOW_LOGPROB_THR,
        "conf_downweight_fact":  CONF_DOWNWEIGHT_FACTOR,
    }
    if run_meta_extra:
        run_meta.update(run_meta_extra)

    logger = DiarioDiBordo(log_dir=SPEECH_LOG_DIR, run_meta=run_meta)
    print(f"\n[LOG] {logger.events_path}\n")
    print("=" * 60)
    print(f"  POLIMILLIONAIRE MASTER — SPEECH — {cat_name} (cat {category_id})")
    print("=" * 60)

    q_idx, current_level, last_outcome = 0, 1, None
    game_completed = False

    while True:
        q_idx += 1
        t0 = time.time()
        print(f"\n[Q{q_idx} | lvl {current_level}] Initiating acoustic data retrieval...")

        # ── Question Retrieval & Transcription
        q_url   = f"{BASE_URL}/api/game/{server_sid}/audio/question"
        q_audio = download_audio(session, q_url)
        if not q_audio:
            print("[TERMINATION] Acoustic payload unavailable. Terminating session.")
            game_completed = True
            break

        raw_q, stt_info_q = transcribe_twice_and_judge(q_audio, cat_name)
        try:
            os.remove(q_audio)
        except OSError:
            pass

        q_text = re.sub(r"\s*option\s+a.*$", "", raw_q, flags=re.IGNORECASE).strip()

        # ── Sequential Download (Mandatory for Server State Machine)
        opt_files = []
        for opt_id in range(4):
            opt_url = f"{BASE_URL}/api/game/{server_sid}/audio/option/next"
            opt_files.append(download_audio(session, opt_url))

        # ── Concurrent Transcription Processing
        q_options       = [None] * 4
        stt_infos_opts  = [None] * 4

        def process_option_task(opt_id: int, opt_audio_path: str):
            """Isolated worker function for threaded transcription."""
            if not opt_audio_path:
                return opt_id, {"id": opt_id, "text": ""}, {"error": "no_audio"}

            # Inject the question text to guide the decoding space
            raw_opt, info_opt = transcribe_robust(
                opt_audio_path, cat_name, use_prompt=True, extra_hint=q_text
            )

            clean = sanitize_option_text(raw_opt)

            # Evaluate acoustic confidence metrics to trigger dynamic beam search expansion
            opt_logprob = info_opt.get("avg_logprob")
            is_acoustic_anomaly = opt_logprob is not None and opt_logprob < LOW_LOGPROB_THR
            need_retry = (not clean or len(clean) < 2 or is_acoustic_anomaly)

            if need_retry:
                reason = "acoustic degradation" if is_acoustic_anomaly else "decoding output anomaly"
                print(f"Option {opt_id} exhibits {reason}. Engaging unprompted retry (beam_size=10).")
                raw2, info2 = transcribe_robust(
                    opt_audio_path, cat_name, use_prompt=False, extra_hint=None, beam_size=10
                )
                clean2 = sanitize_option_text(raw2)
                if clean2:
                    clean = clean2
                    info_opt = {**info_opt, "retry": True, "retry_info": info2}

            try:
                os.remove(opt_audio_path)
            except OSError:
                pass

            return opt_id, {"id": opt_id, "text": clean}, info_opt

        # ThreadPool dispatcher
        with concurrent.futures.ThreadPoolExecutor(max_workers=4) as executor:
            futures = [executor.submit(process_option_task, i, opt_files[i]) for i in range(4)]
            for future in concurrent.futures.as_completed(futures):
                idx, opt_dict, opt_info = future.result()
                q_options[idx] = opt_dict
                stt_infos_opts[idx] = opt_info

        # End of game validation
        if not q_text or not q_options or not q_options[0].get("text"):
            print(f"\n[TERMINATION] Acoustic stream exhausted. Final level: {current_level}.")
            game_completed = True
            break

        t_audio = time.time() - t0
        print(f"\n[Q{q_idx} | lvl {current_level}] "
              f"(Concurrent transcription completed in {t_audio:.1f}s)")
        print(f"  Q: {q_text[:200]}")
        for opt in q_options:
            print(f"  [{opt['id']}] {opt['text']}")
        print("-" * 60)

        # ── LLM Pipeline Processing
        t_qa0 = time.time()
        try:
            chosen, dbg = answer_question(q_text, q_options, category_id,
                                          model, tokenizer)
        except Exception as e:
            print(f"[ERROR] Inference execution failed: {e!r}")
            logger.log_error("answer_question_speech", str(e),
                             extra={"q_idx": q_idx})
            chosen = smart_default_choice(q_options)
            dbg = {"error": str(e), "fallback": "smart_default",
                    "chosen_id": chosen, "confidence": 0.25}
            print(f"Smart fallback activated → Selected option {chosen}")
        elapsed_qa = time.time() - t_qa0

        # ── Confidence Downweighting
        orig_conf = dbg.get("confidence")
        dwn_conf  = downweight_conf_on_bad_stt(orig_conf, stt_info_q, stt_infos_opts)
        if (dwn_conf is not None and orig_conf is not None and dwn_conf < orig_conf):
            print(f"Confidence adjusted: {orig_conf:.2%} → {dwn_conf:.2%} (Acoustic penalization applied)")
            dbg["confidence_pre_downweight"] = orig_conf
            dbg["confidence"]                = dwn_conf

        elapsed_total = t_audio + elapsed_qa
        print(f"\n[DECISION] Option {chosen}  "
              f"[conf {dbg.get('confidence', 0):.2%}]")
        print(f"[ROUTER]   {dbg.get('router_decision','?')}  "
              f"[STT-judge] {stt_info_q.get('judge_decision','single')}")
        bar = ("█" * int(min(elapsed_total / 30.0, 1.0) * 30) +
                "░" * (30 - int(min(elapsed_total / 30.0, 1.0) * 30)))
        status = ("OK"   if elapsed_total < 20 else
                  "WARN" if elapsed_total <= 30 else "FAIL")
        print(f"[METRICS]  {bar} {elapsed_total:.1f}s / 30.0s  "
              f"[STT={t_audio:.1f}s  QA={elapsed_qa:.1f}s]  [{status}]")

        time.sleep(1)
        outcome = submit_answer(session, server_sid, chosen)
        last_outcome = outcome
        if not outcome:
            logger.log_error("submit_answer", "Server connection timeout")
            break

        correct   = bool(outcome.get("correct"))
        new_level = outcome.get("currentLevel")

        logger.log_question(
            question_index=q_idx, level=current_level,
            category_id=category_id, question_text=q_text,
            options=q_options,
            stt_question_info=stt_info_q,
            stt_options_info=stt_infos_opts,
            stt_latency_s=round(t_audio, 3),
            router_decision=dbg.get("router_decision"),
            queries=dbg.get("queries"),
            ner_entities=dbg.get("ner_entities"),
            rag_passages_count=dbg.get("rag_passages_count"),
            rag_sources=dbg.get("rag_sources"),
            faiss_top_score=dbg.get("faiss_top_score"),
            used_online_fallback=dbg.get("used_online_fallback"),
            source_breakdown=dbg.get("source_breakdown"),
            confidence=dbg.get("confidence"),
            confidence_pre_downweight=dbg.get("confidence_pre_downweight"),
            chosen_id_sc=dbg.get("chosen_id_sc"),
            fallback_triggered=dbg.get("fallback_triggered"),
            chosen_option=chosen, mode=dbg.get("mode"),
            timings=dbg.get("timings"),
            inference_time_s=round(elapsed_total, 3),
            qa_time_only_s=round(elapsed_qa, 3),
            correct=correct, new_level=new_level,
            server_payload=outcome,
        )

        if correct:
            print(f"[RESULT] Verification successful → Advancing to level {new_level or 'FINAL'}")
            if new_level is not None:
                current_level = new_level
        else:
            print("[RESULT] Verification failed or timeout exceeded. Session terminated.")
            break

    summary = logger.finalize(final_outcome={
        **(last_outcome or {}),
        "_game_completed": game_completed,
        "_final_level":    current_level,
    })
    print(f"\n[LOGGER] Data serialized to: {logger.events_path}")
    return logger.session_id, summary


