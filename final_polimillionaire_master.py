"""---
# Section 7: Batch Logging

`run_batch_master` is parameterized over the category set, the iteration
count, and the mode (`text` or `speech`). It catches and logs runtime
errors at the per-game level so that a single bad session does not stop
the rest of the batch.

"""

def run_batch_master(n_per_category: int = 10,
                     categories: tuple = (0, 1, 2, 3, 4, 5),
                     mode: str = "text",
                     between_sessions_sleep: float = 5.0,
                     run_meta_extra: dict = None) -> list:
    """Run N sessions × |categories| sessions in sequence. Returns a list of dicts."""
    results = []
    total = len(categories) * n_per_category
    counter = 0
    runner  = run_session_text if mode == "text" else run_session_speech

    for cat in categories:
        for i in range(n_per_category):
            counter += 1
            print(f"\n{'#' * 70}")
            print(f"#  RUN {counter}/{total}  |  cat={cat} ({CATEGORY_NAMES.get(cat, '?')})  "
                  f"|  iter {i + 1}/{n_per_category}  |  mode={mode}")
            print(f"{'#' * 70}")
            try:
                sid, summary = runner(category_id=cat, run_meta_extra=run_meta_extra)
                if summary is not None:
                    results.append({
                        "category":      cat,
                        "iter":          i + 1,
                        "mode":          mode,
                        "session_id":    sid,
                        "accuracy":      summary.get("accuracy"),
                        "max_level":     summary.get("max_level_reached"),
                        "n_questions":   summary.get("questions_attempted"),
                        "avg_inference": summary.get("avg_inference_time_s"),
                        "over_30s":      summary.get("questions_over_30s"),
                    })
                else:
                    results.append({"category": cat, "iter": i + 1,
                                    "mode": mode, "error": "no_summary"})
            except Exception as e:
                print(f"[BATCH ERROR] cat={cat} iter={i + 1}: {e}")
                traceback.print_exc()
                results.append({"category": cat, "iter": i + 1,
                                "mode": mode, "error": str(e)})
            time.sleep(between_sessions_sleep)

    print(f"\n[BATCH] DONE. {len(results)} runs.")
    for r in results:
        if "error" in r:
            print(f"  cat={r['category']} iter={r['iter']}: ERROR {r['error']}")
            continue
        if r.get("accuracy") is not None:
            print(f"  cat={r['category']} iter={r['iter']}: "
                  f"max_lvl={r.get('max_level','?'):>2}  "
                  f"n_q={r.get('n_questions','?'):>2}  "
                  f"acc={r['accuracy']:.0%}  "
                  f"avg_t={r.get('avg_inference','?')}s  "
                  f"over30s={r.get('over_30s','?')}")
    return results

