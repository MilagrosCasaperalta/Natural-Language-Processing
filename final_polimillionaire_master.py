def build_entertainment_corpus(force_rebuild: bool = False):
    if Path(INDEX_ENT_PATH).exists() and Path(CHUNKS_ENT_PATH).exists() and not force_rebuild:
        print(f"[CORPUS-ENT] Index already present at {INDEX_ENT_PATH}")
