"""## 3.6 News pipeline: Local DB → Agentic Scrape → RSS

News questions require evidence past the LLM's knowledge cutoff. The dedicated News architecture relies on a 3-Tier fallback system:

**Tier 1: Local CSV & RSS.** We build a TF-IDF index in RAM at startup from a local export of RSS feeds. We match the query using cosine similarity with a strict threshold (`0.25`). We concurrently pull top items directly from targeted remote RSS feeds.

**Tier 2: Agentic Live Scrape.** Using DuckDuckGo (`ddgs`), we dispatch zero-shot queries (augmented with extracted temporal anchors like dates) to fetch live snippets and full HTML bodies, stripped of boilerplate using BeautifulSoup.

**Tier 3: FAISS Fallback.** If the live tiers don't yield enough confidence, we fall back to a background FAISS general knowledge index to ground historical context in the news.

---

####  Remote fetch concurrency

To guarantee response times inside the 30-second budget, network requests are strictly managed. Both the topical RSS feeds (BBC, The Guardian, AP News, NPR, Al Jazeera) and the DuckDuckGo live agentic searches are executed asynchronously via `ThreadPoolExecutor`. This allows us to saturate the context window with breaking news without suffering compounding network latency.
"""

