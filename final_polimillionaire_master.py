from sklearn.metrics.pairwise import cosine_similarity

class NewsCategoryPipeline:
    """
    Local corpus retrieval pipeline utilizing TF-IDF indexing and cosine similarity.
    Incorporates an on-the-fly extraction protocol to bypass truncation limits.
    """

    LEXICAL_WARN_THR = 0.25  # Strict threshold to prevent contextual contamination

    def __init__(self, csv_path: str):
        print(f"[INITIALIZATION] Instantiating local corpus from data source: {csv_path}")
        self.df = pd.read_csv(csv_path)
        print(f"[INITIALIZATION] Successfully ingested {len(self.df)} records.")

        self.date_col    = next((c for c in ["published_date", "date", "pub_date", "time"]
                                  if c in self.df.columns), None)
        self.title_col   = next((c for c in ["title", "headline", "article_title"]
                                  if c in self.df.columns), self.df.columns[0])
        self.summary_col = next((c for c in ["summary", "description", "snippet"]
                                  if c in self.df.columns), None)
        self.link_col    = next((c for c in ["link", "url", "href", "article_url"]
                                  if c in self.df.columns), None)

        if self.date_col:
            self.df[self.date_col] = pd.to_datetime(self.df[self.date_col], errors="coerce")
            self.df = self.df.dropna(subset=[self.date_col]).sort_values(by=self.date_col)

        if self.summary_col:
            self.df["search_content"] = (self.df[self.title_col].fillna("") + " " +
                                          self.df[self.summary_col].fillna(""))
        else:
            self.df["search_content"] = self.df[self.title_col].fillna("")

        print("[INITIALIZATION] Computing lexical TF-IDF feature matrix...")
        self.vectorizer  = TfidfVectorizer(stop_words="english", max_features=25_000)
        self.tfidf_matrix = self.vectorizer.fit_transform(self.df["search_content"])
        print(f"[INITIALIZATION] Matrix computed. Dimensionality: {self.tfidf_matrix.shape}")

    def search_relevant_article(self, query: str) -> dict:
        """
        Executes a vector search over the local corpus using cosine similarity.
        Applies a hard threshold to discard mathematically weak matches.
        """
        q_vec = self.vectorizer.transform([query])
        sims  = cosine_similarity(q_vec, self.tfidf_matrix).flatten()
        best  = int(sims.argmax())
        score = float(sims[best])

        if score < self.LEXICAL_WARN_THR:
            print(f"[LOCAL RETRIEVAL] Maximum cosine similarity ({score:.3f}) falls below the confidence threshold ({self.LEXICAL_WARN_THR}). Rejecting document to preserve context purity.")
            return {}

        row = self.df.iloc[best].to_dict()
        print(f"[LOCAL RETRIEVAL] Optimal document identified: '{row.get(self.title_col, '?')}' with similarity score {score:.3f}.")
        row["_match_score"] = score
        return row

    def scrape_full_article_body(self, url: str, timeout: int = 4) -> str:
        if not url:
            return ""
        print(f"[EXTRACTION PROTOCOL] Initiating HTTP request to target: {url[:80]}...")
        headers = {"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/91.0.4472.124 Safari/537.36"}
        try:
            r = requests.get(url, headers=headers, timeout=timeout)
            if r.status_code != 200:
                print(f"[EXTRACTION PROTOCOL] Connection rejected. HTTP Status: {r.status_code}")
                return ""
            soup = BeautifulSoup(r.content, "lxml")
            for tag in soup(["script", "style", "noscript", "header", "footer", "nav", "aside"]):
                tag.decompose()
            container = soup.find("article") or soup.find("main") or soup.body
            text = container.get_text(separator=" ", strip=True) if container else ""
            text = re.sub(r"\s+", " ", text)
            print(f"[EXTRACTION PROTOCOL] Payload successfully extracted. Character count: {len(text)}")
            return text[:4000]
        except Exception as e:
            print(f"[EXTRACTION PROTOCOL] Exception occurred during DOM parsing: {e}")
            return ""

    def execute_news_rag_pipeline(self, query: str) -> tuple[str, float]:
        """
        Primary entry point. Returns a tuple containing the formatted textual context
        and the associated cosine similarity score.
        """
        try:
            row = self.search_relevant_article(query)
            if not row:
                return "", 0.0
        except Exception as e:
            print(f"[LOCAL RETRIEVAL] Vector search process failed: {e}")
            return "", 0.0

        url = row.get(self.link_col, "") if self.link_col else ""
        body = self.scrape_full_article_body(url, timeout=4) if url else ""

        title = row.get(self.title_col, "?")
        score = row.get("_match_score", 0.0)

        if body:
            return f"[Source: {title}]\n{body}", score

        title_str = row.get(self.title_col, "")
        summary_str = row.get(self.summary_col, "") if self.summary_col else ""
        return f"[Headline] {title_str}\n[Snippet] {summary_str}".strip(), score


