def _per_option_queries(question_text, options, ner_entities):
    """
    Synthesizes targeted search queries by fusing primary question entities
    with individual option texts to maximize retrieval relevance.
    """
    propers = [e["text"] for e in ner_entities
                if e["label"] in PROPER_NOUN_LABELS
                and len(e["text"].strip()) >= 3]

    propers_str = " ".join(propers[:2]) if propers else question_text[:40]
    out = []

    for opt in options:
        ot = re.sub(r"[^\w\s]", " ", opt.get("text", "")).strip()
        if len(ot) > 60:
            ot = ot[:60]
        q = f"{propers_str} {ot}".strip()
        if 5 <= len(q) <= 100:
            out.append(q)
    return out

