def classify_problem(problem_text: str) -> str:
    """Keyword vote over schemas; ties broken by first definition. -> schema_id."""
    tl = problem_text.lower()
    best_id, best_score = "general", 0
    for s in SCHEMA_DEFINITIONS:
        score = sum(1 for trig in s["triggers"] if trig in tl)
        if score > best_score:
            best_score, best_id = score, s["schema_id"]
    return best_id


