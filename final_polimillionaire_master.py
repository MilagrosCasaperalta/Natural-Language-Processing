"""---
## 8.8 Confidence Calibration: Is the Model Overconfident?

A well-calibrated model should be 80% correct when it says it's 80% confident.

**Key findings:**
- **The model is overconfident:** ECE (Expected Calibration Error) = 13.4%
- **Mean confidence: 96.85%** but actual accuracy is only 83.97%
- **92% of predictions** fall in the 0.9-1.0 confidence bin
- At high confidence (90-100%), actual accuracy is only 87.5%

This is a classic overconfidence pattern — the model "thinks it knows" more than it actually does. The Late-RAG mechanism helps by forcing retrieval when confidence is below the threshold.
"""

# @title
# 8.6 Calibration
confs = np.array([e.get("confidence") for e in events if e.get("confidence") is not None])
corrs = np.array([e.get("correct", False) for e in events if e.get("confidence") is not None])

N_BINS = 10
bin_edges = np.linspace(0, 1, N_BINS+1)
bin_mids = (bin_edges[:-1] + bin_edges[1:]) / 2
bin_accs, bin_counts = np.zeros(N_BINS), np.zeros(N_BINS)

for i in range(N_BINS):
    mask = (confs >= bin_edges[i]) & (confs < bin_edges[i+1]) if i<N_BINS-1 else (confs >= bin_edges[i])
    bin_counts[i] = np.sum(mask)
    bin_accs[i] = np.mean(corrs[mask]) if bin_counts[i]>0 else np.nan

# ECE
ece = 0.0
for i in range(N_BINS):
    mask = (confs >= bin_edges[i]) & (confs < bin_edges[i+1]) if i<N_BINS-1 else (confs >= bin_edges[i])
    n = np.sum(mask)
    if n>0: ece += (n/len(confs)) * abs(np.mean(corrs[mask]) - np.mean(confs[mask]))

fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(10, 10), gridspec_kw={'height_ratios': [3, 1], 'hspace': 0.12})

# Main plot
ax1.plot([0, 1], [0, 1], '--', color='#2c3e50', lw=2, label='Perfect')
w = 0.08
for mid, acc, cnt in zip(bin_mids, bin_accs, bin_counts):
    if np.isnan(acc) or cnt==0: continue
    gap = mid - acc
    if gap > 0:
        ax1.bar(mid, gap, bottom=acc, width=w, color='#e74c3c', alpha=0.5)
        ax1.bar(mid, acc, width=w, color='#2980b9', edgecolor='#34495e')
    else:
        ax1.bar(mid, mid, width=w, color='#2980b9', edgecolor='#34495e')
        ax1.bar(mid, abs(gap), bottom=mid, width=w, color='#3498db', alpha=0.5)

ax1.legend([plt.Line2D([0],[0], linestyle='--', color='#2c3e50', lw=2),
            Patch(facecolor='#2980b9'), Patch(facecolor='#e74c3c', alpha=0.5)],
           ['Perfect', 'Accuracy', 'Overconfident'], loc='upper left')
ax1.set_ylabel('Actual Accuracy')
ax1.set_title('Confidence Calibration', fontsize=16, fontweight='bold')
ax1.text(0.98, 0.02, f'ECE = {ece:.4f}\nn = {len(confs):,}', transform=ax1.transAxes,
        ha='right', va='bottom', bbox=dict(boxstyle='round', facecolor='white'))
ax1.set_xlim(-0.02, 1.02)
ax1.set_ylim(0, 1.05)
ax1.grid(True, alpha=0.3)

