# ─── code extraction / safe exec ────────────────────────────────────────────
def _extract_code(text):
    m = re.search(r"```(?:python)?\s*\n(.*?)```", text, re.DOTALL)
    if m:
        return m.group(1).strip()
    lines = [l for l in text.splitlines()
             if not re.match(r"^\s*(Question|Q|Answer|A|Solution|Explanation)\s*[:\.]",
                             l, re.IGNORECASE)]
    return "\n".join(lines).strip()


def _safe_exec_with_timeout(code_str, timeout_s=6):
    ns = {}
    for stmt in ("import math", "import itertools", "import fractions",
                 "from fractions import Fraction", "import numpy as np",
                 "import sympy as sp", "from sympy import *"):
        try:
            exec(stmt, ns)
        except Exception:
            pass
    try:
        exec("import scipy.stats as stats", ns)
    except Exception:
        pass
    buf, err = io.StringIO(), None

    def _to(signum, frame):
        raise TimeoutError(f"exceeded {timeout_s}s")
    has = hasattr(signal, "SIGALRM")
    if has:
        old = signal.signal(signal.SIGALRM, _to)
        signal.alarm(timeout_s)
    try:
        with contextlib.redirect_stdout(buf):
            exec(code_str, ns)
    except Exception as e:
        err = f"{type(e).__name__}: {e}"
    finally:
        if has:
            signal.alarm(0)
            signal.signal(signal.SIGALRM, old)
    return buf.getvalue().strip(), err


# ─── matching ───────────────────────────────────────────────────────────────
def _value_of(s):
    e, v = latex_to_value(s)
    if v is not None:
        return v
    nums = re.findall(r"-?\d+\.\d+|-?\d+", (s or "").replace("\u2212", "-"))
    return float(nums[0]) if len(nums) == 1 else None


_BOOL = {"true": True, "false": False, "yes": True, "no": False}
def _bools(text):
    return [_BOOL[t] for t in re.findall(r"true|false|yes|no", text.lower())]


def _match_result_to_options(result_str, options):
    if not result_str:
        return None, "empty_output"

    rs = result_str.strip()
    rl = rs.lower()

    # --- 1) BOOLEAN TUPLE MATCHING ---
    ob = _bools(rs)
    if ob and (("(" in rs and ")" in rs) or len(ob) == 2 or rl in ("true", "false")):
        for o in options:
            if _bools(o["text"]) == ob and _bools(o["text"]):
                return o["id"], "tuple_bool"

    # --- 2) EXACT STRING MATCHING (Aggressive Normalization) ---
    def canon(s):
        # Removes spaces, converts to lowercase, and standardizes dashes (en-dash, em-dash, hyphen)
        s = re.sub(r"[\s\u2013\u2014\-]", "-", s.lower())
        # Removes apostrophes, quotation marks, and parentheses for a direct comparison
        return re.sub(r"[()\[\]'\"]", "", s)

    rc = canon(rs)
    for o in options:
        if rc and rc == canon(o["text"]):
            return o["id"], "string_exact_normalized"

    # --- 3) SYMBOLIC & NUMERIC EQUIVALENCE (The SymPy Math Engine) ---
    # Attempts to evaluate the LLM's output as a SymPy expression
    try:
        # Preprocess the output to handle common Python notations
        py_rs = rs.replace("^", "**")
        llm_expr = sp.sympify(py_rs, locals={"sqrt": sp.sqrt, "pi": sp.pi})

        # If it's a pure number, try to extract the float
        tv = None
        if llm_expr.is_number:
            tv = float(llm_expr.evalf())

        best, bestd, second = None, float("inf"), float("inf")

        for o in options:
            # Converts the LaTeX from the option into SymPy
            opt_expr, opt_val = latex_to_value(o["text"])
            if opt_expr is None:
                continue

            # A) Symbolic algebraic equivalence test
            try:
                # If the simplified difference is 0, the expressions are mathematically identical
                diff = sp.simplify(llm_expr - opt_expr)
                if diff == 0:
                    return o["id"], "symbolic_equivalence"
            except Exception:
                pass # If SymPy cannot simplify the expression, proceed to the numerical test

            # B) Numerical proximity test (if both can be evaluated as floats)
            if tv is not None and opt_val is not None:
                d = abs(opt_val - tv)
                if d < bestd:
                    second, bestd, best = bestd, d, o["id"]
                elif d < second:
                    second = d

        if best is not None:
            tol = max(abs(tv) * 1e-4, 1e-6)
            if bestd <= tol and second > bestd + 1e-9:
                return best, "numeric_latex"

    except Exception:
        pass # If the output cannot be parsed by SymPy, proceed

    # --- 4) SUBSTRING MATCHING (Safeguarded) ---
    # Accept the substring only if the LLM's output is reasonably short
    if 4 <= len(rl) <= 60:
        for o in options:
            ol = o["text"].lower()
            if rl in ol or ol in rl:
                return o["id"], "substring_safe"

    return None, "no_match"


# ─── solver with time budget ────────────────────────────────────────────────
def solve_math_with_python(question_text, options, model, tokenizer,
                           max_retries=1, hint="", time_budget_s=18.0):
    """LaTeX-aware math tool. Stops early if `time_budget_s` is exceeded."""
    debug = {"attempts": [], "code_used": None, "exec_output": None,
             "match_kind": None, "model_raw_outputs": []}
    t_start = time.time()

    # auto-augment the hint with evaluated option values (back-solving aid)
    opt_vals = []
    for o in options:
        v = _value_of(o["text"])
        opt_vals.append(f"{o['id']}: {o['text']}"
                        + (f"   (≈ {v:.6g})" if v is not None else ""))
    readable_q = latex_to_readable(question_text)
    q_block = question_text
    if readable_q and readable_q != question_text:
        q_block += f"\n(plain form: {readable_q})"
    opts_str = "\n".join(opt_vals)
    user_msg = f"Question: {q_block}{hint}\nOptions (with numeric values):\n{opts_str}\n\nCode:"

    for attempt in range(max_retries + 1):
        if time.time() - t_start > time_budget_s:
            debug["attempts"].append({"attempt": attempt + 1, "code": "",
                                      "output": "", "error": "time_budget_exceeded",
                                      "match_id": None, "match_kind": None})
            break

        messages = [{"role": "system", "content": MATH_CODE_PROMPT},
                    {"role": "user", "content": user_msg}]
        text = tokenizer.apply_chat_template(messages, tokenize=False,
                                             add_generation_prompt=True)
        inputs = tokenizer([text], return_tensors="pt").to(model.device)
        gen_kwargs = {"max_new_tokens": 320, "pad_token_id": tokenizer.eos_token_id}
        if attempt == 0:
            gen_kwargs["do_sample"] = False
        else:
            gen_kwargs.update({"do_sample": True, "temperature": 0.5, "top_p": 0.9})

        import torch
        with torch.no_grad():
            out = model.generate(**inputs, **gen_kwargs)
        out = [o[len(i):] for i, o in zip(inputs.input_ids, out)]
        raw = tokenizer.batch_decode(out, skip_special_tokens=True)[0]
        debug["model_raw_outputs"].append(raw[:500])

        code_str = _extract_code(raw)
        if not code_str:
            debug["attempts"].append({"attempt": attempt + 1, "code": "",
                                      "output": "", "error": "empty_code_extracted",
                                      "match_id": None, "match_kind": None})
            continue

        output, err = _safe_exec_with_timeout(code_str, timeout_s=6)
        match_id, match_kind = (None, "not_attempted")
        if err is None:
            match_id, match_kind = _match_result_to_options(output, options)
            if match_id is None:
                m = re.fullmatch(r"\s*(\d+)\s*", output)
                if m and any(o["id"] == int(m.group(1)) for o in options):
                    match_id, match_kind = int(m.group(1)), "option_id_fallback"

        debug["attempts"].append({"attempt": attempt + 1, "code": code_str,
                                  "output": output, "error": err,
                                  "match_id": match_id, "match_kind": match_kind})
        print(f"[MATH EXEC] attempt={attempt+1} out={output!r} err={err} "
              f"match={match_id} via {match_kind}")

        if err is None and match_id is not None:
            debug.update({"code_used": code_str, "exec_output": output,
                          "match_kind": match_kind, "n_attempts": attempt + 1})
            return match_id, debug

    debug["n_attempts"] = len(debug["attempts"])
    return None, debug


