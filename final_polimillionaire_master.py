# ─── LaTeX → value converter ───────────────────────────────────────────────
def latex_to_value(s):
    """Convert a (possibly LaTeX) string to (sympy_expr|None, float|None)."""
    if s is None:
        return None, None
    t = s.strip()
    t = (t.replace("$", " ").replace("\\(", " ").replace("\\)", " ")
          .replace("\\[", " ").replace("\\]", " ").replace("~", " ")
          .replace("\\left", "").replace("\\right", "")
          .replace("\\!", "").replace("\\,", "").replace("\\;", ""))
    t = t.replace("\\cdot", "*").replace("\\times", "*").replace("\\div", "/")
    t = t.replace("\\pi", "pi")
    t = t.replace("\\dfrac", "\\frac").replace("\\cfrac", "\\frac").replace("\\tfrac", "\\frac")

    def _bal(e, start):
        depth, i = 0, start
        while i < len(e):
            if e[i] == "{":
                depth += 1
            elif e[i] == "}":
                depth -= 1
                if depth == 0:
                    return e[start + 1:i], i + 1
            i += 1
        return e[start + 1:], len(e)

    def conv(e):
        out, i = "", 0
        while i < len(e):
            if e.startswith("\\frac", i):
                j = i + 5
                while j < len(e) and e[j] == " ":
                    j += 1
                if j < len(e) and e[j] == "{":
                    A, j = _bal(e, j)
                    while j < len(e) and e[j] == " ":
                        j += 1
                    if j < len(e) and e[j] == "{":
                        B, j = _bal(e, j)
                        out += f"(({conv(A)})/({conv(B)}))"
                        i = j
                        continue
            if e.startswith("\\sqrt", i):
                j = i + 5
                root = None
                if j < len(e) and e[j] == "[":
                    k = e.index("]", j)
                    root = e[j + 1:k]
                    j = k + 1
                while j < len(e) and e[j] == " ":
                    j += 1
                if j < len(e) and e[j] == "{":
                    A, j = _bal(e, j)
                    out += (f"sqrt({conv(A)})" if root is None
                            else f"(({conv(A)})**(1/({conv(root)})))")
                    i = j
                    continue
            if e[i] == "\\":
                m = re.match(r"\\[a-zA-Z]+", e[i:])
                if m:
                    i += len(m.group(0))
                    continue
            out += "(" if e[i] == "{" else (")" if e[i] == "}" else e[i])
            i += 1
        return out

    py = conv(t).replace("^", "**")
    py = re.sub(r"\s+", "", py)
    py = re.sub(r"(\d)\(", r"\1*(", py)
    py = re.sub(r"\)(\d)", r")*\1", py)
    py = re.sub(r"(\d)(sqrt|pi)", r"\1*\2", py)
    py = re.sub(r"\)\(", r")*(", py)
    try:
        expr = sp.sympify(py, locals={"sqrt": sp.sqrt, "pi": sp.pi})
        return expr, float(expr.evalf())
    except Exception:
        return None, None


def latex_to_readable(s):
    """Human/LLM-readable rewrite of LaTeX (kept alongside the original)."""
    if not s:
        return s
    t = s.replace("$", "")
    t = t.replace("\\dfrac", "\\frac").replace("\\cfrac", "\\frac").replace("\\tfrac", "\\frac")

    def _bal(e, start):
        depth, i = 0, start
        while i < len(e):
            if e[i] == "{":
                depth += 1
            elif e[i] == "}":
                depth -= 1
                if depth == 0:
                    return e[start + 1:i], i + 1
            i += 1
        return e[start + 1:], len(e)

    def conv(e):
        out, i = "", 0
        while i < len(e):
            if e.startswith("\\frac", i) and i + 5 < len(e):
                j = i + 5
                while j < len(e) and e[j] == " ":
                    j += 1
                if j < len(e) and e[j] == "{":
                    A, j = _bal(e, j)
                    while j < len(e) and e[j] == " ":
                        j += 1
                    if j < len(e) and e[j] == "{":
                        B, j = _bal(e, j)
                        out += f"({conv(A)})/({conv(B)})"
                        i = j
                        continue
            if e.startswith("\\sqrt", i):
                j = i + 5
                root = None
                if j < len(e) and e[j] == "[":
                    k = e.index("]", j)
                    root = e[j + 1:k]
                    j = k + 1
                while j < len(e) and e[j] == " ":
                    j += 1
                if j < len(e) and e[j] == "{":
                    A, j = _bal(e, j)
                    out += (f"sqrt({conv(A)})" if root is None
                            else f"({conv(A)})^(1/{conv(root)})")
                    i = j
                    continue
            if e.startswith("\\cdot", i):
                out += "*"; i += 5; continue
            if e.startswith("\\times", i):
                out += "*"; i += 6; continue
            if e[i] == "\\":
                m = re.match(r"\\[a-zA-Z]+", e[i:])
                if m:
                    out += m.group(0)[1:]; i += len(m.group(0)); continue
            out += e[i]
            i += 1
        return out

    return re.sub(r"\s+", " ", conv(t).replace("~", " ")).strip()


