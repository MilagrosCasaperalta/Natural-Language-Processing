"""## 2.2 `DiarioDiBordo` — structured event logger

The logger is the cornerstone of all downstream evaluation. Each game session
produces:

* `session_<id>.jsonl` — one JSON event per question, including
    * the router decision and its scores,
    * the generated queries and the NER entities,
    * the retrieved passages (source, title, raw and re-ranked scores),
    * the self-consistency vote distribution,
    * the predicted option, the ground truth (`correct`), the confidence,
    * the per-phase latency breakdown.
* `session_<id>_summary.json` — aggregated session metrics (accuracy,
  max level reached, average latency, fallback count, source breakdown).

Every entry carries `run_meta.model_name` so multi-model evaluations
(Section §M, in the companion notebooks) can be merged transparently.

"""

class DiarioDiBordo:
    """Structured JSONL logger for QA sessions.

    Records every routing decision, retrieval call, decoding step, and
    fallback activation, plus a session-level summary for downstream
    aggregation. The schema is versioned (`SCHEMA_VERSION`) to allow
    backwards-compatible analysis across notebook generations.
    """

    SCHEMA_VERSION = "3.1"  # bumped: explicit `model_name` and `prompting_strategy`

    def __init__(self, log_dir=LOG_DIR, run_meta=None):
        self.log_dir = Path(log_dir)
        self.log_dir.mkdir(parents=True, exist_ok=True)
        ts = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
        self.session_id   = f"{ts}_{int(time.time_ns()) % 100000}"
        self.events_path  = self.log_dir / f"session_{self.session_id}.jsonl"
        self.summary_path = self.log_dir / f"session_{self.session_id}_summary.json"
        self.t_start  = time.time()
        self.run_meta = run_meta or {}

        # Aggregates for the summary
        self._n_q = 0; self._n_ok = 0; self._max_lvl = 0
        self._timings = []
        self._calibration_pairs = []
        self._decisions = Counter()
        self._fallback_count = 0
        self._faiss_top_scores = []
        self._source_counter = Counter()
        self._last_outcome = None

        # Identify the experiment in every event — critical for multi-model batches.
        meta_snapshot = {
            "model_name":        self.run_meta.get("model_name"),
            "prompting_strategy": self.run_meta.get("prompting_strategy", "zero_shot_self_consistency"),
            "notebook_label":    self.run_meta.get("notebook_label", "master"),
        }
        self._write_event({
            "event": "session_start",
            "schema_version": self.SCHEMA_VERSION,
            "run_meta": self.run_meta,
            "model_identity": meta_snapshot,
        })

    # ── private write
    def _write_event(self, payload: dict):
        payload = {
            "ts_utc": datetime.now(timezone.utc).isoformat(),
            "session_id": self.session_id,
            "model_name": self.run_meta.get("model_name"),
            **payload,
        }
        with self.events_path.open("a", encoding="utf-8") as f:
            f.write(json.dumps(payload, ensure_ascii=False, default=str) + "\n")

    # ── public API
    def log_question(self, **kw):
        """Log a rich `question_attempted` event."""
        self._n_q += 1
        if kw.get("correct"): self._n_ok += 1
        if (lvl := kw.get("new_level")) and lvl > self._max_lvl: self._max_lvl = lvl
        if (t := kw.get("inference_time_s")) is not None: self._timings.append(t)
        if (decision := kw.get("router_decision")): self._decisions[decision] += 1
        if kw.get("fallback_triggered"): self._fallback_count += 1
        if (s := kw.get("faiss_top_score")) is not None: self._faiss_top_scores.append(s)
        if (conf := kw.get("confidence")) is not None and "correct" in kw:
            self._calibration_pairs.append((float(conf), bool(kw["correct"])))
        for src_name, src_count in (kw.get("source_breakdown", {}) or {}).items():
            self._source_counter[src_name] += src_count
        self._write_event({"event": "question_attempted", **kw})

    def log_thinking(self, q_idx: int, raw_thinking: str, parsed_answer: str = None,
                     extra: dict = None):
        """Specialized event for Chain-of-Thought / thinking-mode logging.

        Used by the dedicated CoT notebook; left here so the logger schema is
        unified across notebooks.
        """
        payload = {
            "event": "thinking_trace",
            "question_index": q_idx,
            "raw_thinking": raw_thinking,
            "raw_thinking_tokens_approx": len(raw_thinking.split()),
            "parsed_answer": parsed_answer,
            "extra": extra or {},
        }
        self._write_event(payload)

    def log_error(self, where: str, message: str, extra: dict = None):
        self._write_event({"event": "error", "where": where,
                           "message": message, "extra": extra or {}})

    def finalize(self, final_outcome: dict = None) -> dict:
        self._last_outcome = final_outcome or {}
        dur = time.time() - self.t_start
        avg_t = (sum(self._timings) / len(self._timings)) if self._timings else None
        summary = {
            "schema_version":           self.SCHEMA_VERSION,
            "session_id":               self.session_id,
            "model_name":               self.run_meta.get("model_name"),
            "started_at_utc":           datetime.fromtimestamp(self.t_start, tz=timezone.utc).isoformat(),
            "ended_at_utc":             datetime.now(timezone.utc).isoformat(),
            "duration_s":               round(dur, 2),
            "run_meta":                 self.run_meta,
            "questions_attempted":      self._n_q,
            "correct_answers":          self._n_ok,
            "accuracy":                 (self._n_ok / self._n_q) if self._n_q else None,
            "max_level_reached":        self._max_lvl,
            "decisions_breakdown":      dict(self._decisions),
            "avg_inference_time_s":     avg_t,
            "questions_over_30s":       sum(1 for t in self._timings if t > 30.0),
            "questions_in_28_30s_band": sum(1 for t in self._timings if 28.0 <= t <= 30.0),
            "fallback_count":           self._fallback_count,
            "avg_faiss_top_score":      (sum(self._faiss_top_scores) / len(self._faiss_top_scores))
                                          if self._faiss_top_scores else None,
            "source_breakdown_total":   dict(self._source_counter),
            "calibration_n":            len(self._calibration_pairs),
            "final_outcome":            self._last_outcome,
        }
        self.summary_path.write_text(
            json.dumps(summary, indent=2, ensure_ascii=False, default=str),
            encoding="utf-8",
        )
        self._write_event({"event": "session_end", "summary": summary})
        return summary

