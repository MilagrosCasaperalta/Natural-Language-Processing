# ═══════════════════════════════════════════════════════════════════════════
#  §6.2 — Speech-mode session runner  (v9-faithful)
# ═══════════════════════════════════════════════════════════════════════════
#  Upgraded implementation featuring concurrent execution and dynamic
#  prompt injection. The server's sequential download requirement is
#  respected, followed by asynchronous multi-threaded transcription.
