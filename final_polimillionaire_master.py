def e5_encode_queries(texts, batch_size: int = 32) -> np.ndarray:
    """Encode user-side texts with the mandatory `query: ` prefix."""
    texts = [f"query: {t}" for t in texts]
    return embedder.encode(texts, normalize_embeddings=True,
                           batch_size=batch_size, convert_to_numpy=True)


def e5_encode_passages(texts, batch_size: int = 32) -> np.ndarray:
    """Encode corpus-side texts with the mandatory `passage: ` prefix."""
    texts = [f"passage: {t}" for t in texts]
    return embedder.encode(texts, normalize_embeddings=True,
                           batch_size=batch_size, convert_to_numpy=True)


