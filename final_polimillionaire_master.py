def _wiki_live(query: str, sentences: int = 10) -> list:
    passages = []
    try:
        r = requests.get(WIKI_API, headers=WIKI_HEADERS, timeout=8, params={
            "action": "query", "list": "search", "srsearch": query,
            "srlimit": 2, "format": "json",
        })
        r.raise_for_status()
        data = r.json()

        if 'query' in data and 'search' in data['query']:
            # Format the results from Wikipedia
            for item in data['query']['search']:
                # Wikipedia snippets contain annoying HTML tags <span class="searchmatch">
                # We remove them using a regex to give the template clean text
                raw_snippet = item.get("snippet", "")
                clean_text = re.sub(r'<[^>]+>', '', raw_snippet)

                passages.append({
                    "source": f"wiki_live:{item.get('title', '?')}",
                    "text": clean_text,
                    "title": item.get("title", ""),
                    "query": query
                })
            return passages
        else:
            return []

    except requests.exceptions.JSONDecodeError:
        print(f"[WIKI_LIVE] JSON Error for '{query}'. Response: {r.text[:200]}")
        return []
    except Exception as e:
        print(f"[WIKI_LIVE] Network error for '{query}': {e}")
        return []
def _ddg(query: str, n: int = 3) -> list:
    out = []
    try:
        from ddgs import DDGS
        for r in (DDGS().text(query, max_results=n) or []):
            body = r.get("body") or ""
            if body:
                out.append({"source": f"ddg:{r.get('href', '')}",
                            "text": body, "query": query})
    except Exception as e:
        print(f"[DDG] '{query}': {e}")
    return out


# ─── Reciprocal Rank Fusion ──────────────────────────────────────────────
def _rrf_merge(dense_ranked: list, sparse_ranked: list, k_rrf: int = 60,
                top_k: int = 20) -> list:
    """Fuse two ranked lists of passage dicts. Identity = `text[:120]`."""
    scores = defaultdict(float)
    by_key = {}
    for rank, p in enumerate(dense_ranked):
        key = p["text"][:120]
        scores[key] += 1.0 / (k_rrf + rank + 1)
        by_key.setdefault(key, p)
    for rank, p in enumerate(sparse_ranked):
        key = p["text"][:120]
        scores[key] += 1.0 / (k_rrf + rank + 1)
        by_key.setdefault(key, p)
    ranked = sorted(scores.items(), key=lambda kv: -kv[1])
    out = []
    for key, s in ranked[:top_k]:
        p = dict(by_key[key])
        p["rrf_score"] = float(s)
        out.append(p)
    return out


# ─── Unified retrieve() — the single entry point used by the pipeline ────
_RETRIEVAL_CACHE: dict = {}


def retrieve(queries: list, entities: list = None, top_k: int = None,
             category_id: int = None, force_online: bool = False) -> dict:
    """Return {passages, top_faiss_score, used_online_fallback, ...}.

    Selects the appropriate corpus by `category_id`:
      * 1  → Ancient History corpus
      * 5  → News pipeline (CSV + RSS + live scrape; see Section 3.5)
      * 0  → Entertainment corpus (with general-Wikipedia backstop)
      * 4  → Philosophy corpus
      * else → General Wikipedia FAISS index
    Always performs Dense+Sparse+RRF on the chosen corpus; activates online
    fallback (Wikipedia API + DDG) when the raw FAISS top score is below
    `FAISS_THRESHOLD` or `force_online=True`.
    """
    top_k = top_k or FAISS_TOP_K
    cache_key = (tuple(sorted(queries)), category_id, force_online)
    if cache_key in _RETRIEVAL_CACHE:
        return _RETRIEVAL_CACHE[cache_key]

    # ── Category 5 (News) → dedicated pipeline (defined in §3.5)
    if category_id == 5 and "news_pipeline" in globals():
        return _retrieve_news(queries, entities, top_k)

    # ── Pick the index + chunks for this category
    if category_id == 1 and "faiss_index_hist" in globals():
        idx_obj, chunks_obj, corpus_label = faiss_index_hist, corpus_chunks_hist, "ancient_history"
    elif category_id == 0 and "faiss_index_ent" in globals():
        idx_obj, chunks_obj, corpus_label = faiss_index_ent, corpus_chunks_ent, "entertainment"
    elif category_id == 4 and "faiss_index_phi" in globals():
        idx_obj, chunks_obj, corpus_label = faiss_index_phi, corpus_chunks_phi, "philosophy"
    else:
        idx_obj, chunks_obj, corpus_label = faiss_index, corpus_chunks, "general_wikipedia"

    t0 = time.time()

    # ── Dense
    q_vecs = e5_encode_queries(queries).astype(np.float32)
    D, I   = idx_obj.search(q_vecs, top_k)
    entity_strs = _entity_strings_for_match(entities)

    dense = []
    for qi, q in enumerate(queries):
        for rank, (s, i) in enumerate(zip(D[qi], I[qi])):
            if i < 0 or i >= len(chunks_obj):
                continue
            c = chunks_obj[i]
            title_lower = (c.get("title") or "").lower()
            matches  = sum(1 for es in entity_strs if es in title_lower)
            raw      = float(s)
            adjusted = raw * (1.0 + TITLE_BONUS_ALPHA * matches)
            dense.append({
                "source":              f"faiss:{c.get('title','?')}",
                "text":                c["text"],
                "title":               c.get("title", ""),
                "url":                 c.get("url", ""),
                "query":               q,
                "faiss_score":         adjusted,
                "faiss_score_raw":     raw,
                "faiss_title_matches": matches,
                "faiss_rank":          rank,
                "corpus":              corpus_label,
            })
    dense.sort(key=lambda x: -x["faiss_score"])
    top_raw = dense[0]["faiss_score_raw"] if dense else 0.0
    top_adj = dense[0]["faiss_score"]     if dense else 0.0

    # ── Sparse — only for medium/large corpora; skip for tiny indices
    sparse = []
    if len(chunks_obj) >= 1000:
        try:
            tfidf_vec, tfidf_mat = _get_tfidf_index(chunks_obj)
            qmat = tfidf_vec.transform(queries)
            sim  = cosine_similarity(qmat, tfidf_mat)
            for qi, q in enumerate(queries):
                top_sparse_idx = sim[qi].argsort()[-top_k:][::-1]
                for rank, di in enumerate(top_sparse_idx):
                    c = chunks_obj[di]
                    sparse.append({
                        "source": f"tfidf:{c.get('title','?')}",
                        "text":   c["text"],
                        "title":  c.get("title", ""),
                        "url":    c.get("url", ""),
                        "query":  q,
                        "tfidf_score":  float(sim[qi][di]),
                        "tfidf_rank":   rank,
                        "corpus":       corpus_label,
                    })
        except Exception as e:
            print(f"[SPARSE WARN] {e}")

    # ── RRF fusion (or just dense if no sparse)
    if sparse:
        fused = _rrf_merge(dense, sparse, k_rrf=60, top_k=top_k * 2)
    else:
        fused = dense[: top_k * 2]

    # ── Online fallback when retrieval looks weak
    used_fallback = False
    if force_online or top_raw < FAISS_THRESHOLD or len(fused) < 3:
        used_fallback = True
        with ThreadPoolExecutor(max_workers=4) as ex:
            futs = []
            for q in queries:
                futs.append(ex.submit(_wiki_live, q))
                futs.append(ex.submit(_ddg, q))
            for f in as_completed(futs, timeout=12):
                try:
                    fused.extend(f.result())
                except Exception as e:
                    print(f"[RETRIEVE] task: {e}")

    result = {
        "passages":              fused,
        "top_faiss_score":       top_adj,
        "top_faiss_score_raw":   top_raw,
        "used_online_fallback":  used_fallback,
        "corpus":                corpus_label,
        "retrieve_time_s":       round(time.time() - t0, 3),
    }
    _RETRIEVAL_CACHE[cache_key] = result
    return result

"""## 2.7 Cross-encoder reranking

The cross-encoder receives the question + concatenated option text as the
query side, and the candidate passage on the document side. Empirically the
option-augmented query lifts top-1 reranking accuracy by a small but
consistent margin because the reranker can exploit lexical overlap with the
correct option.

"""

def rerank_passages(question_text: str, options: list, passages: list,
                    top_k: int = None) -> list:
    """Score each passage against `question + options text` with the cross-encoder."""
    top_k = top_k or RERANK_TOP_K
    if not passages:
        return []
    opts_text = " ".join(o["text"] for o in options)
    query = f"{question_text} {opts_text}"
    pairs  = [[query, p["text"][:512]] for p in passages]
    scores = reranker.predict(pairs, batch_size=16, show_progress_bar=False)
    for p, s in zip(passages, scores):
        p["rerank_score"] = float(s)
    passages.sort(key=lambda x: -x["rerank_score"])
    return passages[:top_k]

"""## 2.8 Self-consistency decoder

  Naive top-1 generation is unstable on multiple-choice questions: the model's
  preferred option flips between greedy runs when two options have similar
  likelihood. We extract the logits over the `{0, 1, 2, 3}` digit tokens
  directly from a **single forward pass**, then sample `SC_SAMPLES` votes
  from a temperature-softened version of that distribution.

  **Default:** `SC_SAMPLES = 5`, `SC_TEMPERATURE = 0.8`
  
  **Entertainment override:** `SC_SAMPLES = 9`, `SC_TEMPERATURE = 0.4` (more stable on pop-culture
  trivia)

  Final confidence is the weighted combination:

  $$\text{conf} = 0.6 \cdot p_{\text{greedy}}(\text{argmax}) + 0.4 \cdot
  \frac{\text{votes}_{\text{argmax}}}{N}$$

  This gives a calibrated, cheap signal (one forward pass + N RNG draws —
  sub-millisecond) that downstream stages can use to decide whether to
  trigger fallbacks.
"""

@torch.no_grad()
def _logit_distribution(question_text: str, options: list, context: str,
                        model, tokenizer):
    """Single forward pass; return (chosen_id, p_hard, p_soft, raw_decoded)."""
    if not options:
        raise ValueError("_logit_distribution: empty options list (game ended).")
    options_text = "\n".join(f"Option {o['id']}: {o['text']}" for o in options)
    sys_msg = (
        "You are an expert quiz player. Use the provided context if relevant; "
        "otherwise rely on your own knowledge. Reply with ONLY the single digit "
        "ID of the correct option. No words, no punctuation."
    )
    user_msg = (
        f"Context:\n{context}\n\nQuestion: {question_text}\n\n"
        f"Options:\n{options_text}\n\nAnswer (single digit only):"
    )
    messages = [{"role": "system", "content": sys_msg},
                {"role": "user",   "content": user_msg}]
    text = tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
    inputs = tokenizer([text], return_tensors="pt").to(model.device)
    out = model(**inputs)
    last_logits = out.logits[0, -1, :].float()

    valid_ids = [o["id"] for o in options]
    digit_token_ids = {}
    for oid in valid_ids:
        toks = tokenizer.encode(str(oid), add_special_tokens=False)
        if toks:
            digit_token_ids[oid] = toks[0]

    if not valid_ids or len(digit_token_ids) != len(valid_ids):
        # Fallback to greedy text generation, then parse the first digit.
        with torch.no_grad():
            gen = model.generate(**inputs, max_new_tokens=5, do_sample=False,
                                 pad_token_id=tokenizer.eos_token_id)
        gen = [g[len(i):] for i, g in zip(inputs.input_ids, gen)]
        raw = tokenizer.batch_decode(gen, skip_special_tokens=True)[0]
        m = re.search(r"\d+", raw)
        cid = int(m.group()) if (m and int(m.group()) in valid_ids) else valid_ids[0]
        uniform = {oid: 1.0 / len(valid_ids) for oid in valid_ids}
        return cid, uniform, uniform.copy(), raw

    logits = torch.stack([last_logits[digit_token_ids[oid]] for oid in valid_ids])
    probs_hard = torch.softmax(logits, dim=-1).cpu().numpy()
    probs_sc   = torch.softmax(logits / LOGIT_T_DECIDE, dim=-1).cpu().numpy()
    p_hard = {int(o): float(p) for o, p in zip(valid_ids, probs_hard)}
    p_sc   = {int(o): float(p) for o, p in zip(valid_ids, probs_sc)}
    return valid_ids[int(np.argmax(probs_hard))], p_hard, p_sc, ""


def self_consistency_decide(question_text: str, options: list, context: str,
                            model, tokenizer, n_samples: int = None,
                            temperature: float = None) -> tuple:
    """One forward pass + N temperature-softened samples, soft-voted."""
    n_samples   = n_samples   or SC_SAMPLES
    temperature = temperature or SC_TEMPERATURE
    valid_ids = [o["id"] for o in options]

    _, probs_hard, _, raw = _logit_distribution(
        question_text, options, context, model, tokenizer
    )

    # Re-softmax with the desired sampling temperature
    logits_back = np.array([math.log(max(probs_hard[o], 1e-9)) for o in valid_ids])
    scaled  = logits_back / temperature
    p_sample = np.exp(scaled - scaled.max())
    p_sample = p_sample / p_sample.sum()

    rng = np.random.default_rng()
    samples = rng.choice(valid_ids, size=n_samples, p=p_sample)
    votes = Counter(samples.tolist())
    chosen_id = votes.most_common(1)[0][0]
    vote_distribution = {oid: votes.get(oid, 0) / n_samples for oid in valid_ids}

    confidence_hard  = probs_hard[chosen_id]
    confidence_votes = vote_distribution[chosen_id]
    confidence = 0.6 * confidence_hard + 0.4 * confidence_votes

    return chosen_id, {
        "chosen_id":            chosen_id,
        "probs_hard":           probs_hard,
        "vote_distribution":    vote_distribution,
        "confidence_hard":      confidence_hard,
        "confidence_votes":     confidence_votes,
        "confidence":           confidence,
        "n_samples":            n_samples,
        "sampling_temperature": temperature,
        "raw_output":           raw,
    }

"""  ## 2.9 Option-grounded fallback

  When the self-consistency confidence is below `CONFIDENCE_THR = 0.55` and we
  still have at least 8 seconds of budget, we switch from "pick a digit" to
  "evaluate each candidate independently". For each option we retrieve a tiny
  option-specific context, ask the model whether the context supports the
  candidate (binary `{0, 1}` logit comparison), and pick the option with the
  highest $p_{\text{yes}}$. The benefit is that the model no longer needs to
  emit a digit in the presence of distractors; the evidence aggregation
  happens externally.
"""

@torch.no_grad()
def option_grounded_evaluate(question_text: str, options: list,
                              model, tokenizer) -> tuple:
    """For each option, compute p(yes | context, candidate). Pick the max."""
    def _search_one(opt):
        q = f"{question_text} {opt['text']}"
        result = retrieve([q], top_k=4)
        passages = result["passages"][:3]
        ctx = " ".join(p["text"][:400] for p in passages) or "No context found."
        return opt, ctx

    with ThreadPoolExecutor(max_workers=4) as ex:
        results = list(ex.map(_search_one, options))

    yes_tok = tokenizer.encode("1", add_special_tokens=False)[0]
    no_tok  = tokenizer.encode("0", add_special_tokens=False)[0]

    scores, per_opt_debug = [], []
    for opt, ctx in results:
        sys_msg = (
            "You are a fact-checking assistant. Given context and a candidate "
            "answer, reply with ONLY a single digit: 1 if the context supports "
            "the candidate, 0 otherwise. No words."
        )
        user_msg = (
            f"Context:\n{ctx}\n\nQuestion: {question_text}\n"
            f"Candidate answer: {opt['text']}\n\nReply (1 or 0):"
        )
        messages = [{"role": "system", "content": sys_msg},
                    {"role": "user",   "content": user_msg}]
        text = tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
        inputs = tokenizer([text], return_tensors="pt").to(model.device)
        out = model(**inputs)
        last_logits = out.logits[0, -1, :].float()
        two = torch.tensor([last_logits[yes_tok], last_logits[no_tok]])
        p_yes = float(torch.softmax(two, dim=-1)[0])
        scores.append((opt["id"], p_yes))
        per_opt_debug.append({
            "id": opt["id"], "text": opt["text"],
            "context_preview": ctx[:200], "p_yes": p_yes,
        })
    scores.sort(key=lambda x: -x[1])
    return scores[0][0], {
        "per_option": per_opt_debug,
        "chosen_id":  scores[0][0],
        "best_p_yes": scores[0][1],
    }

