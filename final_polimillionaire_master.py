"""## 2.4 Embedding-based router

The router decides which downstream solver to engage. We embed a small set of
prototype questions per intent (`MATH`, `RAG`, `MEMORY`), average them into
a unit vector, and at inference time pick the highest-similarity intent.

For Maths (category 3) we **bypass** the embedding step and shortcut to
`MATH`, because the server-side category is authoritative and avoids
mis-routing when the question text is ambiguous (e.g. statement-style
algebra problems can look like factual recall).

"""

ROUTER_PROTOTYPES = {
    "MATH": [
        "Compute the value of an integral",
        "What is the result of this arithmetic operation",
        "Solve this equation for x",
        "Calculate the probability",
        "What is the derivative of this function",
    ],
    "RAG": [
        "In which year did this historical event take place",
        "Who was the king or emperor of this country",
        "What ancient civilization built this monument",
        "Which scientist discovered this principle",
        "What is the capital of this country and when was it founded",
        "Which movie won the Academy Award in this year",
        "Who wrote this novel and when was it published",
    ],
    "MEMORY": [
        "Which character appears in this TV show",
        "What is a common-sense everyday question",
        "Identify a basic word definition",
        "Solve this simple logic puzzle",
    ],
}


def build_router_prototypes() -> dict:
    proto = {}
    for label, texts in ROUTER_PROTOTYPES.items():
        vecs = e5_encode_queries(texts)
        mean = vecs.mean(axis=0)
        mean = mean / (np.linalg.norm(mean) + 1e-9)
        proto[label] = mean
    Path(ROUTER_PROTO).parent.mkdir(parents=True, exist_ok=True)
    with open(ROUTER_PROTO, "wb") as f:
        pickle.dump(proto, f)
    return proto


def load_router_prototypes() -> dict:
    if Path(ROUTER_PROTO).exists():
        with open(ROUTER_PROTO, "rb") as f:
            return pickle.load(f)
    return build_router_prototypes()


router_proto = load_router_prototypes()
print(f"[ROUTER] Prototypes ready: {list(router_proto.keys())}")


def embedding_router(question_text: str, category_id: int) -> tuple:
    """Return (label, scores). Maths is hard-shortcut by category id."""
    if category_id == 3:
        return "MATH", {"MATH": 1.0}
    q_vec = e5_encode_queries([question_text])[0]
    scores = {label: float(np.dot(q_vec, v)) for label, v in router_proto.items()}
    scores.pop("MATH", None)  # Maths is reachable only via category_id == 3
    return max(scores, key=scores.get), scores

"""## 2.5 Query generation with NER cleanup

We ask the LLM to produce two complementary queries (broad subject vs.
narrow detail) using a 3-shot prompt, then optionally append a third
NER-derived query. The NER pipeline is filtered to remove the failure mode
documented in the source notebook: spaCy occasionally aggregates option
words into a fake PERSON entity (e.g. `"Bronze Iron Copper" → PERSON`),
which then turns the third query into a paraphrase of the option list and
poisons retrieval. The `_filter_entities_for_query` helper enforces three
rules: drop entities shorter than 3 chars, drop digit-only entities, drop
entities whose words substantially overlap with the option text.

"""

FEW_SHOT_QUERY_PROMPT = """You generate web search queries to answer multiple-choice quiz questions.
For each question, output TWO complementary queries:
- QUERY1: focuses on the main subject/entity (broad)
- QUERY2: focuses on the specific detail asked (narrow)

Each query is 3-7 words, no quotes, no punctuation. Use entities from the OPTIONS when they help disambiguate.

Examples:

Question: What was the primary reason for Nirvana's name change from Skid Row to Nirvana?
Options:
0: There was already a band called Skid Row
1: They wanted a Buddhist reference
2: Their record label demanded it
3: A bet with another musician
QUERY1: Nirvana band name origin
QUERY2: Skid Row Nirvana renamed reason

Question: Which Italian physicist won the Nobel Prize in 1938?
Options:
0: Galileo Galilei
1: Enrico Fermi
2: Guglielmo Marconi
3: Alessandro Volta
QUERY1: Italian Nobel Prize physics 1938
QUERY2: Enrico Fermi Nobel Prize physics

Question: In what year was the Treaty of Westphalia signed?
Options:
0: 1618
1: 1648
2: 1689
3: 1715
QUERY1: Treaty of Westphalia year
QUERY2: Peace of Westphalia 1648

Now generate for the next question.
"""

PROPER_NOUN_LABELS = {"PERSON", "ORG", "GPE", "LOC", "EVENT",
                      "WORK_OF_ART", "FAC", "PRODUCT", "NORP"}


def extract_entities(text: str) -> list:
    """Run spaCy NER and keep semantically informative labels."""
    doc = nlp(text)
    return [{"text": e.text, "label": e.label_} for e in doc.ents
            if e.label_ in PROPER_NOUN_LABELS | {"DATE"}]


def _option_words(options: list) -> set:
    """Set of (lowercased, len > 2) tokens from all options. Used to detect
    NER mislabels that bleed in from the option list."""
    words = set()
    for o in options:
        for w in re.findall(r'\w+', o['text'].lower()):
            if len(w) > 2:
                words.add(w)
    return words


def _filter_entities_for_query(entities: list, options: list) -> list:
    """Keep only entities that are (a) >= 3 chars, (b) not digit-only,
    (c) not substantially overlapping with the option text."""
    opt_w = _option_words(options)
    cleaned = []
    for e in entities:
        t = e['text'].strip()
        if len(t) < 3:                                       continue
        if t.replace('.', '').replace('-', '').isdigit():    continue
        words = [w for w in re.findall(r'\w+', t.lower()) if len(w) > 2]
        if not words:                                        continue
        overlap = sum(1 for w in words if w in opt_w)
        if overlap / len(words) > 0.5:                       continue
        cleaned.append(e)
    return cleaned


def generate_search_queries(question_text: str, options: list,
                            model, tokenizer) -> tuple:
    """Return (queries, all_ner_entities).

    Queries: 2 LLM-generated + optionally 1 NER-derived. All entities (not
    only the filtered ones) are returned so that the downstream retrieval
    can use them for the title-match bonus.
    """
    full_text = question_text + " " + " ".join(o['text'] for o in options)
    entities = extract_entities(full_text)

    opts_str = "\n".join(f"{o['id']}: {o['text']}" for o in options)
    user_msg = f"Question: {question_text}\nOptions:\n{opts_str}\nQUERY1:"
    messages = [
        {"role": "system", "content": FEW_SHOT_QUERY_PROMPT},
        {"role": "user",   "content": user_msg},
    ]
    text = tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
    inputs = tokenizer([text], return_tensors="pt").to(model.device)
    with torch.no_grad():
        out = model.generate(**inputs, max_new_tokens=40, do_sample=False,
                             pad_token_id=tokenizer.eos_token_id)
    out = [o[len(i):] for i, o in zip(inputs.input_ids, out)]
    raw = tokenizer.batch_decode(out, skip_special_tokens=True)[0]

    queries = []
    parts = raw.split("QUERY2:")
    q1 = re.sub(r'^QUERY\s*1?\s*:\s*', '', parts[0].strip().split("\n")[0],
                flags=re.IGNORECASE).strip()
    if q1: queries.append(q1)
    if len(parts) > 1:
        q2 = re.sub(r'^QUERY\s*2?\s*:\s*', '', parts[1].strip().split("\n")[0],
                    flags=re.IGNORECASE).strip()
        if q2 and q2.lower() != q1.lower(): queries.append(q2)
    if not queries:
        queries = [question_text[:80]]

    useful = _filter_entities_for_query(entities, options)
    if 2 <= len(useful) <= 4:
        ner_query = " ".join(e["text"] for e in useful[:4])
        if (ner_query.lower() not in {q.lower() for q in queries}
                and 3 <= len(ner_query) <= 80):
            queries.append(ner_query)

    return queries, entities

"""## 2.6 Hybrid retrieval: Dense + Sparse + Reciprocal Rank Fusion

This is the central retrieval module. It combines:

1. **Option-anchored queries**: each option text is concatenated with the
   question, so retrieval is biased toward localizing evidence per option
   rather than for the question only.
2. **Dense search** over a FAISS `IndexFlatIP` (inner product on
   `e5-base-v2` normalised vectors).
3. **An entity-in-title bonus**

   $\text{adj} = \text{raw} \cdot (1 + \alpha \cdot m)$
   with $\alpha = 0.40$ and $m$ = number of NER entities appearing in the chunk's title. This fixes the recurring failure mode where a query matched purely on the lexical surface of a proper noun.
4. **Sparse search** with a TF-IDF cosine similarity matrix, fitted once at
   bootstrap. This is the path that recovers exact-match cues (proper nouns,
   numbers, years) that dense embeddings smooth away.
5. **Reciprocal Rank Fusion** with smoothing constant $k_{\text{RRF}} = 60$,
   merging the two ranked lists into a robust final ordering.
6. **Dynamic Online Fallback**: If the top raw FAISS score falls below `FAISS_THRESHOLD` (or if too few passages are found), the pipeline dynamically triggers live searches via Wikipedia API and DuckDuckGo to inject fresh context.
"""

# ─── Title-match bonus helpers ───────────────────────────────────────────
def _entity_strings_for_match(entities: list) -> list:
    """Normalize NER entities to lowercase substrings for title matching."""
    if not entities:
        return []
    keep = {"PERSON", "ORG", "GPE", "LOC", "FAC", "WORK_OF_ART", "EVENT", "PRODUCT"}
    out = []
    for e in entities:
        if e.get("label") not in keep:
            continue
        t = re.sub(r"[''`\"]s?\b", "", e["text"]).strip().lower()
        if len(t) >= 3 and not t.replace(".", "").isdigit():
            out.append(t)
    return out


# ─── Sparse TF-IDF index, built lazily on first call ─────────────────────
_TFIDF_CACHE: dict = {}


def _get_tfidf_index(corpus_chunks: list) -> tuple:
    """Return (vectorizer, matrix) cached by corpus identity."""
    key = id(corpus_chunks)
    if key not in _TFIDF_CACHE:
        print(f"[SPARSE] Building TF-IDF index over {len(corpus_chunks)} chunks ...")
        texts = [c["text"] for c in corpus_chunks]
        vec = TfidfVectorizer(stop_words="english", max_features=50_000)
        mat = vec.fit_transform(texts)
        _TFIDF_CACHE[key] = (vec, mat)
        print(f"[SPARSE] TF-IDF matrix ready: shape={mat.shape}")
    return _TFIDF_CACHE[key]


# ─── Dense FAISS lookup with entity-in-title bonus ───────────────────────
def _faiss_search(queries: list, entities: list = None,
                           k: int = None) -> list:
    """Dense search over the general Wikipedia FAISS index."""
    k = k or FAISS_TOP_K
    vecs = e5_encode_queries(queries)
    scores, idx = faiss_index.search(vecs.astype(np.float32), k)
    entity_strs = _entity_strings_for_match(entities)
    results, seen = [], set()
    for qi, q in enumerate(queries):
        for rank, (s, i) in enumerate(zip(scores[qi], idx[qi])):
            if i < 0 or i in seen:
                continue
            seen.add(i)
            c = corpus_chunks[i]
            title_lower = c["title"].lower()
            matches = sum(1 for es in entity_strs if es in title_lower)
            raw = float(s)
            adjusted = raw * (1.0 + TITLE_BONUS_ALPHA * matches)
            results.append({
                "source":              f"faiss:{c['title']}",
                "text":                c["text"],
                "title":               c["title"],
                "url":                 c.get("url", ""),
                "query":               q,
                "faiss_score":         adjusted,
                "faiss_score_raw":     raw,
                "faiss_title_matches": matches,
                "faiss_rank":          rank,
            })
    results.sort(key=lambda x: -x["faiss_score"])
    return results


